const counterObserver = new IntersectionObserver(entries => {
  entries.forEach(en => {
    if (en.isIntersecting){
      const el = en.target;
      const target = parseFloat(el.dataset.target);
      const decimals = +(el.dataset.decimal || 0);
      let cur = 0;
      const step = target / 60;
      const tick = () => {
        cur += step;
        if (cur >= target){ el.textContent = target.toLocaleString('en-US', {minimumFractionDigits:decimals, maximumFractionDigits:decimals}); return; }
        el.textContent = cur.toLocaleString('en-US', {minimumFractionDigits:decimals, maximumFractionDigits:decimals});
        requestAnimationFrame(tick);
      };
      tick();
      counterObserver.unobserve(el);
    }
  });
}, { threshold: 0.5 });
document.querySelectorAll('.counter').forEach(el => counterObserver.observe(el));
