function addToCart(id, qty = 1){
  const item = cart.find(c => c.id === id);
  item ? item.qty += qty : cart.push({ id, qty });
  updateCounts(); renderCart(); openDrawer('cart');
}
function changeQty(id, delta){
  const item = cart.find(c => c.id === id);
  if (!item) return;
  item.qty += delta;
  if (item.qty <= 0) cart = cart.filter(c => c.id !== id);
  updateCounts(); renderCart();
}
function removeFromCart(id){ cart = cart.filter(c => c.id !== id); updateCounts(); renderCart(); }

function cartTotals(){
  const subtotal = cart.reduce((s,c) => s + findProduct(c.id).price * c.qty, 0);
  const discount = couponApplied ? Math.round(subtotal * couponApplied.pct) : 0;
  return { subtotal, discount, total: subtotal - discount };
}

function renderCart(){
  const wrap = document.getElementById('cartItems');
  document.getElementById('cartEmpty').classList.toggle('hidden', cart.length !== 0);
  wrap.innerHTML = cart.map(c => {
    const p = findProduct(c.id);
    return `<div class="flex gap-3 items-center border-b border-brand-50 pb-4">
      <img src="${p.img}" class="w-16 h-16 rounded-xl object-cover">
      <div class="flex-1">
        <p class="font-semibold text-sm">${p.name}</p>
        <p class="text-brand-700/60 text-xs">${money(p.price)}</p>
        <div class="flex items-center border border-brand-200 rounded-full w-fit mt-1.5">
          <button onclick="changeQty('${c.id}',-1)" class="w-7 h-7 text-sm">−</button>
          <span class="w-6 text-center text-sm font-semibold">${c.qty}</span>
          <button onclick="changeQty('${c.id}',1)" class="w-7 h-7 text-sm">+</button>
        </div>
      </div>
      <button onclick="removeFromCart('${c.id}')" class="text-brand-400 hover:text-red-400 text-lg leading-none">✕</button>
    </div>`;
  }).join('');
  const { subtotal, discount, total } = cartTotals();
  document.getElementById('cartSubtotal').textContent = money(subtotal);
  document.getElementById('cartTotal').textContent = money(total);
  document.getElementById('discountRow').classList.toggle('hidden', !couponApplied);
  if (couponApplied) document.getElementById('cartDiscount').textContent = '-' + money(discount);
}

