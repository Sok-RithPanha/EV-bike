async function placeOrder(e){
  e.preventDefault();
  
  // 1. Grab all the data the user typed into the form
  const form = document.getElementById('shippingForm');
  const inputs = form.querySelectorAll('input');
  
  const fullName = inputs[0].value;
  const email = inputs[1].value;
  const streetAddress = inputs[2].value;
  const city = inputs[3].value;
  const zipCode = inputs[4].value;
  
  // Find which payment method they selected
  const checkedPayment = form.querySelector('input[name="pay"]:checked');
  const paymentMethod = checkedPayment ? checkedPayment.parentElement.textContent.trim() : 'Card';
  
  const totals = cartTotals();
  
  // 2. Package it all up into a nice JSON object
  const orderData = {
    fullName: fullName,
    email: email,
    streetAddress: streetAddress,
    city: city,
    zipCode: zipCode,
    paymentMethod: paymentMethod,
    subtotal: totals.subtotal,
    discount: totals.discount,
    total: totals.total,
    items: cart.map(item => {
      const p = findProduct(item.id);
      return {
        id: item.id,
        qty: item.qty,
        price: p ? p.price : 0
      };
    })
  };

  try {
    // 3. Send the packaged data to your Python server
    const response = await fetch('https://ev-bike.onrender.com//api/orders', {
      method: 'POST',
      headers: {
        'Content-Type': 'application/json'
      },
      body: JSON.stringify(orderData)
    });

    if (!response.ok) {
      throw new Error('Failed to record order in backend');
    }

    // 4. If successful, hide the form and show the success screen
    document.getElementById('checkoutForm').classList.add('hidden');
    const success = document.getElementById('orderSuccess');
    success.classList.remove('hidden'); 
    success.classList.add('page-fade');
    
    // Clear the cart out
    cart = []; 
    couponApplied = null; 
    updateCounts(); 
    renderCart();

  } catch (error) {
    console.error('Checkout error:', error);
    alert('There was an error placing your order. Please try again.');
  }

  return false;
}

