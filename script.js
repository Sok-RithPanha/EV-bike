const state = { language: 'en' };

function t(key) {
  const lang = translations[state.language] || translations.en;
  return (lang[key] || translations.en[key] || key);
}

function translatePage() {
  document.documentElement.lang = state.language === 'km' ? 'km' : 'en';
  document.querySelectorAll('[data-i18n]').forEach(el => {
    const key = el.dataset.i18n;
    const value = t(key);
    if (value && value.includes('<br>')) {
      el.innerHTML = value;
    } else {
      el.textContent = value;
    }
  });

  document.querySelectorAll('[data-i18n-placeholder]').forEach(el => {
    el.setAttribute('placeholder', t(el.dataset.i18nPlaceholder));
  });

  const languageSelect = document.getElementById('languageSelect');
  if (languageSelect) languageSelect.value = state.language;

  const currentCountText = document.getElementById('compareCount');
  if (currentCountText) {
    const existingText = currentCountText.textContent || '';
    const countMatch = existingText.match(/\d+/);
    const count = countMatch ? Number(countMatch[0]) : 0;
    currentCountText.textContent = t('compareCount').replace('{count}', count);
  }

  const searchInput = document.getElementById('searchInput');
  if (searchInput && !searchInput.matches(':focus')) {
    const placeholder = t('searchPlaceholder');
    searchInput.setAttribute('placeholder', placeholder);
  }
}

function setLanguage(lang){
  state.language = lang in translations ? lang : 'en';
  translatePage();
}

