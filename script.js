let PRODUCTS = [];

async function loadProducts() {
  try {
    const response = await fetch('https://your-api-url.com/api/products');
    if (!response.ok) {
      throw new Error(`HTTP ${response.status}`);
    }

    const payload = await response.json();
    const apiProducts = Array.isArray(payload) ? payload : Array.isArray(payload.products) ? payload.products : [];

    PRODUCTS = apiProducts.map((p, index) => ({
      id: String(p.id ?? p.product_id ?? `p${index + 1}`),
      name: p.name ?? p.model ?? 'Unnamed bike',
      category: p.category ?? p.type ?? 'General',
      price: Number(p.price ?? 0),
      rating: Number(p.rating ?? 4.5),
      popularity: Number(p.popularity ?? 80),
      dateAdded: Number(p.dateAdded ?? p.date_added ?? index + 1),
      stock: Boolean(p.stock ?? p.in_stock ?? true),
      img: p.img ?? p.image ?? './Landing.png',
      badge: p.badge ?? '',
      range: p.range ?? '0-0',
      topSpeed: Number(p.topSpeed ?? p.top_speed ?? 0),
      charging_time: p.charging_time ?? p.chargingTime ?? 'N/A',
      weight: p.weight ?? 'N/A',
      desc: p.desc ?? p.description ?? 'Premium electric bike.'
    }));

    renderProductFilters();
    renderProducts();
  } catch (error) {
    console.error('Failed to load products from API', error);
    PRODUCTS = [];
    renderProductFilters();
    renderProducts();
  }
}

